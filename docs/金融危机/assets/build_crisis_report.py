def phase_behavior(s):
    """危机前期/中期/后期行为标注"""
    d, e, r = s["def_score"], s["el_score"], s["risk_score"]
    ind = s["ind"]
    # 前期（泡沫高位）：高风险高Beta先跌
    if r >= 60: pre = "大跌(高Beta)"
    elif r >= 48: pre = "承压回落"
    elif d >= 72: pre = "抗跌"
    else: pre = "小幅震荡"
    # 中期（恐慌期）：防御高抗跌
    if d >= 72 and r < 45: mid = "抗跌领涨"
    elif d >= 62: mid = "相对抗跌"
    elif r >= 55: mid = "深跌"
    else: mid = "随盘下跌"
    # 后期（政策底后）：弹性高反弹强
    if e >= 75: post = "大反弹(弹性先锋)"
    elif e >= 62: post = "强反弹"
    elif d >= 72 and r < 40: post = "稳健修复"
    elif e >= 50: post = "中幅修复"
    else: post = "弱势反弹"
    return pre, mid, post

