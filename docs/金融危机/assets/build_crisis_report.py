def classify(s):
    """按危机三阶段行为分类"""
    d, e, r = s["def_score"], s["el_score"], s["risk_score"]
    if d >= 80 or (d >= 75 and r <= 30): return "避险核心"
    if d >= 68 and r < 45: return "稳健防御"
    if e >= 72 and r >= 45: return "高弹性反弹"
