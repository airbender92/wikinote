def calc_scores(item):
    code,name,ind,price,pe,pb,div,mv,roe,h52,l52,ytd = item
    df,el,beta,desc = INDUSTRY[ind]
    if pe <= 0: pe_score = 30
    elif pe <= 8: pe_score = 100
    elif pe <= 15: pe_score = 85
    elif pe <= 25: pe_score = 65
    elif pe <= 40: pe_score = 40
    else: pe_score = 20
    div_score = min(100, div * 12)
    roe_score = min(100, roe * 4)
    val_score = pe_score*0.6 + (100-min(100,pb*15))*0.4
    def_score = df*40 + val_score*0.20 + div_score*0.20 + roe_score*0.20
    def_score = round(min(100, def_score*0.85 + df*15),1)
    drawdown = max(0, (h52-price)/h52*100)
    rebound_score = min(100, drawdown*1.8)
    el_score = round(min(100, el*40 + rebound_score*0.30 + roe_score*0.15 + beta*15),1)
    if pe <= 0: risk_pe = 100
    elif pe >= 60: risk_pe = 90
    elif pe >= 40: risk_pe = 70
    elif pe >= 25: risk_pe = 50
    elif pe >= 15: risk_pe = 30
    else: risk_pe = 15
    risk_score = round(min(100, beta*40 + risk_pe*0.30 + (60 if ind in ("bro","tech","mat","ship","chem","auto") else 25)*0.30),1)
    return dict(code=code,name=name,ind=ind,desc=desc,price=price,pe=pe,pb=pb,div=div,mv=mv,
                roe=roe,h52=h52,l52=l52,ytd=ytd,def_score=def_score,el_score=el_score,
                risk_score=risk_score,drawdown=round(drawdown,1))

