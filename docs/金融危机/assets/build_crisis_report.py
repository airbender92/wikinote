def low_suck_zone(s):
    """低吸区间：按风险分决定回撤深度。返回(下沿, 上沿)相对当前价"""
    risk = s["risk_score"]
    if s["cat"] == "避险核心": lo_dd, hi_dd = 0.10, 0.18
    elif s["cat"] == "稳健防御": lo_dd, hi_dd = 0.12, 0.22
    elif s["cat"] == "攻守兼备": lo_dd, hi_dd = 0.15, 0.28
    elif s["cat"] == "高弹性反弹": lo_dd, hi_dd = 0.20, 0.35
    else: lo_dd, hi_dd = 0.22, 0.38
    upper = s["price"] * (1 - lo_dd)   # 回撤较浅一档 = 区间上沿（先买点）
    lower = s["price"] * (1 - hi_dd)   # 回撤较深一档 = 区间下沿（重仓点）
    # 同时参考52周低点：区间下沿不应远低于52周低点（极端情况除外）
    lower = max(lower, s["l52"] * 0.85)
    return round(lower,2), round(upper,2)

