def calc(s):
    code,name,board,price,pe,pb,div,mv,roe,h52,l52,ytd,tag = s
    df,el,beta,desc = TAG[tag]
    if pe <= 0: pe_s = 20
    elif pe <= 15: pe_s = 100
    elif pe <= 30: pe_s = 70
    elif pe <= 60: pe_s = 45
    elif pe <= 120: pe_s = 25
    else: pe_s = 10
    div_s = min(100, div*12)
    roe_s = min(100, roe*4)
    def_score = round(min(100, df*40 + pe_s*0.20 + div_s*0.15 + roe_s*0.25),1)
    drawdown = max(0,(h52-price)/h52*100)
    rebound_s = min(100, drawdown*1.6)
    el_score = round(min(100, el*42 + rebound_s*0.28 + roe_s*0.15 + beta*15),1)
    if pe <= 0: risk_pe = 100
    elif pe >= 200: risk_pe = 95
    elif pe >= 100: risk_pe = 80
    elif pe >= 60: risk_pe = 60
    elif pe >= 30: risk_pe = 40
    else: risk_pe = 20
    risk_score = round(min(100, beta*45 + risk_pe*0.35 + 20),1)
    # 分类
    if risk_score >= 75: cat = "泡沫高危(最深跌)"
    elif el_score >= 75: cat = "高弹性进攻"
    elif risk_score >= 55: cat = "高风险高弹性"
    else: cat = "攻守平衡"
    # 三阶段
    if risk_score >= 75: pre = "高位深跌"
    elif risk_score >= 55: pre = "高位回落"
    else: pre = "震荡分化"
    if risk_score >= 65: mid = "恐慌深跌"
    elif df >= 0.5: mid = "相对抗跌"
    else: mid = "随盘下跌"
    if el_score >= 78: post = "大反弹(先锋)"
    elif el_score >= 62: post = "强反弹"
    else: post = "修复反弹"
    # 低吸区间：科技高波动，回撤更深
    if cat == "泡沫高危": lo_dd, hi_dd = 0.30, 0.50
    elif cat == "高弹性进攻": lo_dd, hi_dd = 0.25, 0.42
    elif cat == "高风险高弹性": lo_dd, hi_dd = 0.22, 0.38
    else: lo_dd, hi_dd = 0.18, 0.32
    upper = price*(1-lo_dd)
    lower = max(price*(1-hi_dd), l52*0.85)
    if lower >= upper:
        upper = lower * 1.15
    return dict(code=code,name=name,board=board,price=price,pe=pe,pb=pb,div=div,mv=mv,
                roe=roe,h52=h52,l52=l52,ytd=ytd,tag=tag,desc=desc,def_score=def_score,
                el_score=el_score,risk_score=risk_score,cat=cat,pre=pre,mid=mid,post=post,
                low_zone=(round(lower,2),round(upper,2)))

