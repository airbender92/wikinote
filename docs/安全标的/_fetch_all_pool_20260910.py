def build_symbols(codes):
    out=[]
    for c in codes:
        if c.startswith(("6","9")):
            out.append("sh"+c)
        else:
            out.append("sz"+c)
    return out

symbols = build_symbols([c for c,_,_,_,_ in POOL])
# 腾讯接口，分批≤20
results={}
for i in range(0, len(symbols), 20):
    batch = symbols[i:i+20]
    url = "http://qt.gtimg.cn/q=" + ",".join(batch)
    req = urllib.request.Request(url, headers={"User-Agent":"Mozilla/5.0"})
    data = urllib.request.urlopen(req, timeout=10).read().decode("gbk", errors="ignore")
    for line in data.split(";"):
        line=line.strip()
        if "=" not in line or '"' not in line:
            continue
        body = line.split('="',1)[1].rstrip('"')
        f = body.split("~")
        if len(f) < 33:
            continue
        code = f[2]
        name = f[1]
        price = f[3]
        pct = f[32]
        results[code] = (name, float(price), float(pct))

print("代码\t名称\t现价\t涨跌%\t低吸区间\t状态\t备注")
for code,name,lo,hi,note in POOL:
    if code not in results:
        print(f"{code}\t{name}\tN/A\tN/A\t{lo}~{hi}\t无数据\t{note}")
        continue
    nm, price, pct = results[code]
    if price < lo:
        st = "跌破下沿"
    elif price > hi:
        st = "涨出上沿"
    else:
        st = "区间内"
    # 距下沿/上沿
    print(f"{code}\t{nm}\t{price:.2f}\t{pct:+.2f}%\t{lo}~{hi}\t{st}\t{note}")
